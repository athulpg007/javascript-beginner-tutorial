console.log("1" == 1); // loose equality: true, because of type coercion
console.log("1" === 1); // strict equality: false, no type coercion

console.log(1 > 0); // greater than: true
console.log("1" > 0); // greater than: true
console.log(1 < 2); // less than: true
console.log("1" < 2); // less than: true